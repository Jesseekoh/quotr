async function SeedInverters() {
  console.log(`Seeding ${inverters.length} inverter products...`);

  const data = inverters.map((product) => {
    const {
      costPrice,
      discountPrice,
      resalePrice,
      specialPrice,
      enduserPrice,
    } = product;
    return {
      userId,
      name: product.name,
      brand: product.brand,
      category: product.category,
      specification: product.specification,
      warranty: product.warranty,
      unit: product.unit,
      technicalSpecs: product.technicalSpecs,
      costPrice,
      discountPrice,
      resalePrice,
      specialPrice,
      enduserPrice,
    };
  });
  await prisma.product.createMany({
    data,
  });

  console.log(`Successfully seeded ${data.length} products.`);
}

async function SeedSolarPanels() {
  console.log(`Seeding ${solarPanels.length} solar panel products...`);

  const data = solarPanels.map((product) => {
    const [costPrice, discountPrice, resalePrice, specialPrice, enduserPrice] =
      product.prices;

    const [
      costPricePerWatt,
      discountPricePerWatt,
      resalePricePerWatt,
      specialPricePerWatt,
      enduserPricePerWatt,
    ] = product.pricePerWatt;

    return {
      userId,
      name: `${product.brand} ${product.wattage}W Solar Panel`,
      brand: product.brand,
      category: ProductCategory.SOLAR_PANEL,
      specification: product.specification,
      warranty: 'N/A',
      unit: 'pcs',

      technicalSpecs: {
        wattage: product.wattage,
        power: `${product.wattage}W`,
        pricePerWatt: {
          costPrice: costPricePerWatt,
          discountPrice: discountPricePerWatt,
          resalePrice: resalePricePerWatt,
          specialPrice: specialPricePerWatt,
          enduserPrice: enduserPricePerWatt,
        },
      },

      costPrice,
      discountPrice,
      resalePrice,
      specialPrice,
      enduserPrice,
    };
  });

  await prisma.product.createMany({
    data,
  });

  console.log(`Successfully seeded ${data.length} products.`);
}

async function main() {
  await SeedInverters();
  await SeedSolarPanels();
}

main()
  .catch((error) => {
    console.error('Seed failed:', error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
